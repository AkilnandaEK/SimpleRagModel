# Individual criteria
# ---------------------------------------------------------------------------

def check_code_sample_parses(answer: str) -> dict[str, Any]:
    """Assertion A — every detected code sample in the answer parses."""
    blocks = extract_code_blocks(answer)
    criterion = "code_sample_parses"

    if not blocks:
        return {
            "criterion": criterion,
            "applicable": False,
            "passed": None,
            "details": "no code sample in answer; nothing to parse",
        }

    failures: list[str] = []
    parsed_count = 0
    for language, code in blocks:
        lang = language or "python"
        # Markdown code fences are frequently indented (e.g. inside a list
        # item). Remove only the common leading indent before parsing so that a
        # validly-indented sample is not falsely rejected; internal indentation
        # (which would be a real parse error) is preserved by dedent().
        code = textwrap.dedent(code)
        try:
            if lang == "json":
                json.loads(code)
            elif lang in ("sh", "bash", "shell", "zsh"):
                # No reliable safe parser is available; validate basic structure only.
                # We do NOT execute anything. A blank/whitespace body is fine.
                if not code.strip():
                    failures.append(f"{lang}: empty shell block")
                parsed_count += 0  # untested language — not counted as parsed
                continue
            elif lang in ("python", "py", "") and _looks_like_python(code):
                ast.parse(code)
                parsed_count += 1
            else:
                # Unknown language without a reliable parser — skip, don't fail.
                continue
        except (SyntaxError, ValueError, json.JSONDecodeError) as exc:
            failures.append(f"{lang or 'python'}: {exc}")

    if failures:
        return {
            "criterion": criterion,
            "applicable": True,
            "passed": False,
            "details": "code sample failed to parse: " + "; ".join(failures),
        }
    if parsed_count == 0 and not blocks:
        return {
            "criterion": criterion,
            "applicable": False,
            "passed": None,
            "details": "no code sample in answer; nothing to parse",
        }
    return {
        "criterion": criterion,
        "applicable": True,
        "passed": True,
        "details": f"{len(blocks)} code block(s) present; {parsed_count} parsed ok",
    }


def _looks_like_python(code: str) -> bool:
    # Only attempt the AST parse if the block plausibly contains Python
    # (assignment, import, def, method call, keyword) — avoids false failures on
    # prose accidentally fenced without a language tag.
    return bool(
        re.search(
            r"(?m)^\s*(import |from |def |class |@|if |for |while |try:|[A-Za-z_]\w*\s*=|[A-Za-z_]\w*\()",
            code,
        )
    )


def check_endpoint_exists(answer: str) -> dict[str, Any]:
    """Assertion B — every endpoint path mentioned exists in the OpenAPI spec."""
    criterion = "endpoint_exists"
    references = extract_endpoint_paths(answer)
    if not references:
        return {
            "criterion": criterion,
            "applicable": False,
            "passed": None,
            "details": "no endpoint path found in answer; nothing to check",
        }

    pairs, bare_paths = _openapi_paths()
    method_index = {(m, p) for m, p in pairs}
    missing: list[str] = []
    for method, path in references:
        found = False
        if method and (method, path) in method_index:
            found = True
        elif path in bare_paths:
            found = True
        if not found:
            missing.append(f"{method + ' ' if method else ''}{path}")

    if missing:
        return {
            "criterion": criterion,
            "applicable": True,
            "passed": False,
            "details": "endpoint(s) not in OpenAPI spec: " + "; ".join(missing),
        }
    return {
        "criterion": criterion,
        "applicable": True,
        "passed": True,
        "details": f"all {len(references)} endpoint reference(s) exist in the OpenAPI spec",
    }


def check_api_version_stated(answer: str, required_version: str = API_VERSION) -> dict[str, Any]:
    """Assertion C — the required API version is explicitly stated in the answer.

    Only meaningful when the eval case requires a version; the caller decides
    applicability. We do NOT count a bare ``/v3/`` inside an endpoint path as
    stating the version.
    """
    criterion = "api_version_stated"
    lowered = (answer or "").lower()
    version_digits = re.search(r"\d+", required_version)
    need = version_digits.group(0) if version_digits else required_version

    # "v3", "SDK v3", "API v3" — the v-token must NOT be inside a path segment
    # (no preceding '/') nor a sub-token of a longer word (e.g. "v3mod").
    v_form = rf"(?<![A-Za-z0-9_./-])v\s*{need}(?![A-Za-z0-9_./-])"
    # "version 3", "API 3", "SDK 3" stated in words. The trailing \b accepts a
    # minor suffix like "version 3.5" as a correct major version.
    word_form = rf"\b(?:version|api|sdk)\s*(?:v)?{need}\b"
    stated = re.search(rf"(?i){v_form}|{word_form}", lowered)

    if stated:
        return {
            "criterion": criterion,
            "applicable": True,
            "passed": True,
            "details": f"answer states API version {required_version}",
        }

    # A different major version explicitly stated (e.g. v2 / version 2).
    other = re.search(
        rf"(?i)(?<![A-Za-z0-9_./-])v\s*([2-9])\b|\b(?:version|api|sdk)\s*(?:v)?([2-9])\b",
        lowered,
    )
    if other:
        broken = getattr(other, "group")(1) or getattr(other, "group")(2)
        return {
            "criterion": criterion,
            "applicable": True,
            "passed": False,
            "details": f"answer states a wrong version (v{broken}); expected {required_version}",
        }
    return {
        "criterion": criterion,
        "applicable": True,
        "passed": False,
        "details": f"answer does not explicitly state the required API version ({required_version})",
    }


def check_deprecated_symbol_migration(answer: str, deprecations: list[dict[str, str]] | None = None) -> dict[str, Any]:
    """Assertion D — deprecated symbols, if referenced, carry a migration note.

    ``deprecations`` is the real repository deprecation list (currently empty).
    """
    criterion = "deprecated_symbol_migration"
    if deprecations is None:
        deprecations = load_deprecations()

    mentioned = [d for d in deprecations if re.search(rf"\b{re.escape(d['symbol'])}\b", answer)]
    if not mentioned:
        return {
            "criterion": criterion,
            "applicable": False,
            "passed": None,
            "details": "no deprecated symbol referenced in answer",
        }

    lowered = answer.lower()
    missing_notes: list[str] = []
    for item in mentioned:
        has_note = False
        # A migration/deprecation note = the word "deprecat*" or "use ... instead".
        if "deprecat" in lowered:
            has_note = True
        replacement = item.get("replacement")
        if replacement and f"use {replacement}".lower() in lowered:
            has_note = True
        if not has_note:
            missing_notes.append(
                f"'{item['symbol']}' deprecated but no migration/deprecation note found"
            )

    if missing_notes:
        return {
            "criterion": criterion,
            "applicable": True,
            "passed": False,
            "details": "; ".join(missing_notes),
        }
    return {
        "criterion": criterion,
        "applicable": True,
        "passed": True,
        "details": f"all {len(mentioned)} mentioned deprecated symbol(s) carry a migration note",
    }


# ---------------------------------------------------------------------------
# Orchestration
# ---------------------------------------------------------------------------

def run_assertions(case: dict, answer: str) -> dict[str, dict[str, Any]]:
    """Run all four deterministic assertions for a single eval case + its answer.

    Returns ``{"<criterion>": result_dict, ...}``. Applicability of
    ``api_version_stated`` is determined by the case: only ``version_specific``
    cases require the version to be stated.
    """
    results: dict[str, dict[str, Any]] = {}

    results["code_sample_parses"] = check_code_sample_parses(answer)
    results["endpoint_exists"] = check_endpoint_exists(answer)

    requires_version = case.get("taxonomy_mode") == "version_specific"
    if requires_version:
        results["api_version_stated"] = check_api_version_stated(answer, API_VERSION)
    else:
        results["api_version_stated"] = {
            "criterion": "api_version_stated",
            "applicable": False,
            "passed": None,
            "details": "case does not require the API version to be stated",
        }

    results["deprecated_symbol_migration"] = check_deprecated_symbol_migration(answer)

    return results
