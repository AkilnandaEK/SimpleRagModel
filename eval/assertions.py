"""
eval/assertions.py
------------------
Week 6 · Work Item 3 — Deterministic assertion layer for the docs-answer
evaluation.

These are criteria a normal program can check reliably and cheaply, so they do
NOT need an LLM judge. When the LLM judge is implemented later, these criteria
must be EXCLUDED from the judge prompt.

Criteria implemented
--------------------
  code_sample_parses        A — code blocks in the answer parse successfully.
  endpoint_exists           B — endpoint paths in the answer exist in OpenAPI.
  api_version_stated        C — the required API version is stated when needed.
  deprecated_symbol_migration D — deprecated symbols are accompanied by a
                                  migration/deprecation note.

Every check is deterministic and side-effect free. Verified sources of truth
(no invented data):

  * OpenAPI:      the real spec auto-generated by the FastAPI app
                  (``app.openapi()``) — covers POST /upload, POST /query,
                  GET /collections, DELETE /collections/{collection_name},
                  GET /eval/golden-set, GET /eval/mrr, GET /.
  * API version:  the real SDK version, ``v3`` — stated throughout
                  docs/v3_sdk/*.md and in every chunk's ``sdk_version``
                  metadata.
  * Deprecations: the real repository deprecation list. The docs contain NO
                  deprecation markers, so this list is currently EMPTY. The
                  check is written generically so it becomes active the moment
                  deprecation data is added to the docs.

Result shape (uniform for all criteria)::

    {
      "criterion": "<name>",
      "applicable": bool,     # False => nothing to check, not a pass/fail
      "passed": bool | None,  # None when not applicable
      "details": str
    }

No model-generated code is ever executed — only parsed (AST / JSON).
"""

from __future__ import annotations

import ast
import json
import re
import textwrap
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent

#: The deterministic assertion criteria (Work Item 3). The four criteria that
#: are moved OUT of the LLM judge. The judge, when added later, must NOT re-judge
#: these.
ASSERTION_CRITERIA = [
    "code_sample_parses",
    "endpoint_exists",
    "api_version_stated",
    "deprecated_symbol_migration",
]

#: The real project API version, taken from docs/v3_sdk/*.md and the chunks'
#: ``sdk_version: v3`` metadata.
API_VERSION = "v3"


# ---------------------------------------------------------------------------
# Real sources of truth
# ---------------------------------------------------------------------------

def _openapi_paths() -> tuple[list[tuple[str, str]], set[str]]:
    """Return the project's real OpenAPI endpoints: (method, path) pairs and
    the set of bare path strings."""
    from app.main import app  # local import to keep the module import-light

    spec = app.openapi()
    pairs: list[tuple[str, str]] = []
    for path, operations in (spec.get("paths") or {}).items():
        for method in ("get", "post", "put", "patch", "delete", "head", "options"):
            if method in operations:
                pairs.append((method.upper(), path))
    bare = {path for _, path in pairs}
    return pairs, bare


def load_deprecations() -> list[dict[str, str]]:
    """Load the real deprecation list by scanning the SDK documentation.

    Returns a list of ``{"symbol": ..., "replacement": ...}``. Today the docs
    contain no deprecation markers, so this returns an empty list (the real
    state of the repository). The parser is written so any future
    ``deprecated``/``use X instead`` wording in the docs is picked up.
    """
    deprecations: list[dict[str, str]] = []
    docs_dir = ROOT / "docs" / "v3_sdk"
    if not docs_dir.exists():
        return deprecations

    # Match: "old_name is deprecated; use new_name instead" (plus variants).
    pattern = re.compile(
        r"(?ix)\b([A-Za-z_][\w.]*)"
        r"(?:\s+(?:is|are|was)\s+deprecated|\(deprecated\))"
        r"(?:\s*;\s*|\s*,?\s+use\s+|\s*->\s*use\s+)"
        r"([A-Za-z_][\w.(]*?)"
    )
    for path in sorted(docs_dir.glob("*.md")):
        text = path.read_text(encoding="utf-8")
        for match in pattern.finditer(text.replace("\n", " ")):
            deprecations.append(
                {"symbol": match.group(1), "replacement": match.group(2), "source": path.name}
            )
    return deprecations


# ---------------------------------------------------------------------------
# Extraction helpers
# ---------------------------------------------------------------------------

def extract_code_blocks(answer: str) -> list[tuple[str, str]]:
    """Return ``(language, code)`` tuples for every fenced code block.

    Handles ```python```, ```json```, ```bash``` etc. and unlabelled blocks.
    """
    blocks: list[tuple[str, str]] = []
    pattern = re.compile(r"```([\w+-]*)\s*\n(.*?)```", re.DOTALL)
    for match in pattern.finditer(answer):
        language = match.group(1).strip().lower() or None
        code = match.group(2).strip("\n")
        blocks.append((language, code))
    return blocks


def extract_endpoint_paths(answer: str) -> list[tuple[str | None, str]]:
    """Extract endpoint references from the answer.

    Returns a list of ``(method_or_None, normalized_path)``. Handles::

        POST /v3/recipes/search
        GET /v3/users
        /v3/users
        `/v3/users`

    If an endpoint cannot be confidently extracted it is simply not returned
    (nothing is invented).
    """
    found: list[tuple[str | None, str]] = []
    # METHOD /path  (method explicitly stated)
    method_re = re.compile(r"(?i)\b(GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)\s+`?([A-Za-z0-9_./{}-]+)`?")
    # bare /path  (no method)
    bare_re = re.compile(r"`?(/(?:[A-Za-z0-9_.{}-]+/)*[A-Za-z0-9_{}.-]*)`?")

    for match in method_re.finditer(answer):
        path = match.group(2).strip()
        found.append((match.group(1).upper(), path))

    # Only add bare paths not already captured (fingerprint to avoid dupes).
    seen = set(found)
    for match in bare_re.finditer(answer):
        path = match.group(1).strip()
        if (None, path) not in seen:
            found.append((None, path))
            seen.add((None, path))
    return found


